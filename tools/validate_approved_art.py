#!/usr/bin/env python3
"""Validate the five approved Frontier Mountain source sprite sheets.
Copy unchanged PNG files from the project Library into assets/approved_sprites/
before running. No new artwork is generated by this script.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parents[1] / "assets" / "approved_sprites"
EXPECTED = {
    "frontier_lumberjack_sprite_sheet.png": ("de876a417322c4c3a8fd966fb5e574696d99c1b8e130be528b1d45f2a90e34f8", 1839875),
    "frontier_mountain_asset_sheet.png": ("a3c7fb7e44594c3b48106dfe9d6278beec7354598f2713c243decf9227ddbee1", 2476946),
    "frontier_mountain_building_sprite_sheet.png": ("77502c1ebf4a5c7d9d45d9f23e474ee4a3da756a14953fd7eb675d5f7448945c", 2370996),
    "frontier_mountain_logger_sprite_atlas.png": ("da921cee652a52165dca3db26a59cb3eed96d72dd082e17e3aba089e038846a1", 1883894),
    "pixel_art_tree_felling_and_logging_atlas.png": ("799d99836dc3870dc3026c4f59cad3c04992520727e0f3f7e1f78071a2ef6bb8", 2562583),
}
errors = []
for name, (expected_hash, expected_size) in EXPECTED.items():
    path = ROOT / name
    if not path.is_file():
        errors.append(f"MISSING {name}")
        continue
    data = path.read_bytes()
    if len(data) != expected_size or hashlib.sha256(data).hexdigest() != expected_hash:
        errors.append(f"CHANGED {name}")
    else:
        print(f"APPROVED {name}")
if errors:
    print("\n".join(errors), file=sys.stderr)
    sys.exit(1)
print("All five original approved sheets validated.")
